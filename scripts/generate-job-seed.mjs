// Generates supabase/migrations/0003_seed_jobs.sql from the starter listings in src/data/jobs.js.
// Usage: node scripts/generate-job-seed.mjs
import { writeFileSync } from 'node:fs';
import { seedJobs } from '../src/data/jobs.js';

const str = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => (a.length ? `array[${a.map(str).join(', ')}]::text[]` : `'{}'::text[]`);

const rows = seedJobs.map((j) =>
  `  (${[
    str(j.id), str(j.title), str(j.industry), str(j.employer), str(j.city), str(j.state),
    j.remote, str(j.type), str(j.schedule), j.payMin, j.payMax, str(j.payUnit), str(j.summary),
    arr(j.responsibilities), arr(j.requirements), arr(j.benefits), j.urgent, str(j.recruiterId),
    `now() - interval '${j.postedDaysAgo} days'`,
  ].join(', ')})`
);

const sql = `-- Orovelia: starter job listings (generated by scripts/generate-job-seed.mjs — do not edit by hand).
-- Run after 0002_marketplace.sql. Re-running leaves existing jobs untouched.

insert into public.jobs (
  id, title, industry, employer, city, state, remote, type, schedule, pay_min, pay_max, pay_unit,
  summary, responsibilities, requirements, benefits, urgent, recruiter_id, created_at
)
values
${rows.join(',\n')}
on conflict (id) do nothing;
`;

writeFileSync(new URL('../supabase/migrations/0003_seed_jobs.sql', import.meta.url), sql);
console.log(`Wrote ${rows.length} jobs.`);
